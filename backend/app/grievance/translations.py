def translate_grievance_string(
    english: str,
    lang: str,
    map_name: str | None = None,
) -> str:
    """Look up a static translation for a known English grievance string.

    This is the AUTHORITATIVE translation source.  External API translation
    is only an enhancement for strings NOT in these maps.

    Args:
        english: The English string to translate.
        lang: Target language code (en, hi, gu, mr, bn, ta).
        map_name: Optional hint to narrow the lookup ("category",
                  "subcategory", "department", "jurisdiction", "title",
                  "field_label", "portal_name", "submission_step",
                  "timeline", "disclaimer").  If ``None``, all maps are searched.

    Returns:
        Translated string if found, otherwise the original English string.
    """
    if lang == "en":
        return english

    maps = []
    if map_name == "category" or map_name is None:
        maps.append(CATEGORY)
    if map_name == "subcategory" or map_name is None:
        maps.append(SUBCATEGORY)
    if map_name == "department" or map_name is None:
        maps.append(DEPARTMENT)
    if map_name == "jurisdiction" or map_name is None:
        maps.append(JURISDICTION)
    if map_name == "title" or map_name is None:
        maps.append(TITLE)
    if map_name == "field_label" or map_name is None:
        maps.append(FIELD_LABEL)
    if map_name == "field_prompt" or map_name is None:
        maps.append(FIELD_PROMPTS)
    if map_name == "portal_name" or map_name is None:
        maps.append(PORTAL_NAME)
    if map_name == "submission_step" or map_name is None:
        maps.append(SUBMISSION_STEPS)
    if map_name == "followup_prefix" or map_name is None:
        maps.append(FOLLOWUP_PREFIX)
    if map_name == "workflow_prefix" or map_name is None:
        maps.append(WORKFLOW_PREFIX)
    if map_name == "timeline" or map_name is None:
        maps.append(TIMELINE)
    if map_name == "disclaimer" or map_name is None:
        maps.append(DISCLAIMER)

    for m in maps:
        entry = m.get(english)
        if entry and lang in entry:
            return entry[lang]

    return english


def translate_field_label(field_key: str, lang: str) -> str:
    """Translate a field label by its snake_case key."""
    if lang == "en":
        labels = FIELD_LABEL.get(field_key, {})
        return labels.get("en", field_key.replace("_", " ").title())
    entry = FIELD_LABEL.get(field_key)
    if entry and lang in entry:
        return entry[lang]
    # Fallback: title-case the key
    return field_key.replace("_", " ").title()


def translate_template(template_key: str, lang: str, **kwargs: str) -> str:
    """Look up a localized template and fill in dynamic placeholders.

    Args:
        template_key: Key in the TEMPLATE map.
        lang: Target language code.
        **kwargs: Placeholder values to substitute (e.g. authority="X", city="Y").

    Returns:
        The localized, filled-in string.  If the template or language
        is missing, returns the English template with values filled in.
    """
    entry = TEMPLATE.get(template_key)
    if entry:
        template = entry.get(lang) or entry.get("en", "")
    else:
        template = ""
    try:
        return template.format(**kwargs)
    except KeyError:
        return template


def translate_field_prompt(field_key: str, lang: str, english_prompt: str) -> str:
    """Translate a field prompt using the static FIELD_PROMPTS map.

    For known prompts, the static map provides deterministic translations
    in all supported languages.  For unknown prompts, the original English
    prompt is returned.
    """
    if lang == "en":
        return english_prompt
    entry = FIELD_PROMPTS.get(english_prompt)
    if entry and lang in entry:
        return entry[lang]
    return english_prompt
